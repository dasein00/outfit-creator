def grams(prod, amount, unit):
    g = prod["gramsPerUnit"]
    return {"г": amount, "мл": amount, "кг": amount * 1000, "л": amount * 1000, "шт": amount * (g if g > 0 else 100),
            "ст.л.": amount * 15, "ч.л.": amount * 5, "стакан": amount * 200, "щепотка": amount}.get(unit, 0)

out = []
for rec in R:
    ingr = []
    tot = dict(kcal=0, protein=0, fat=0, carbs=0)
    for n, a, u in rec["ingredients"]:
        p = PRODUCTS[n]
        g = grams(p, a, u)
        ingr.append(dict(product=n, amount=a, unit=u, grams=round(g, 1)))
        for k in tot: tot[k] += p[k] * g / 100
    rec["ingredients"] = ingr
    out.append(rec)
    ps = {k: round(v / rec["servings"]) for k, v in tot.items()}
    print(f'{rec["name"][:42]:42s} {rec["servings"]}п  {ps}')
json.dump(dict(version=1, products=list(PRODUCTS.values()), recipes=out), open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '../../app/src/main/assets/recipes/seed.json'), 'w'), ensure_ascii=False, separators=(',', ':'))
