/** Инструкция к разделу: что это, как пользоваться по шагам и полезные советы. */
data class HowToGuide(val title: String, val about: String, val steps: List<String>, val tips: List<String> = emptyList())

/**
 * Блок «Как пользоваться» в конце раздела. Всегда начинается свёрнутым;
 * нажатие раскрывает подробную инструкцию (состояние запоминается).
 */
@Composable
fun HowTo(key: String, modifier: Modifier = Modifier.padding(top = 20.dp, bottom = 12.dp)) {
    val g = HowToTexts.all[key] ?: return
    val extra = LocalExtra.current
    var open by rememberUiFlag("howto_$key", false)
    Column(modifier.fillMaxWidth().clip(RoundedCornerShape(14.dp)).background(MaterialTheme.colorScheme.primary.copy(alpha = .07f))) {
        Row(
            Modifier.fillMaxWidth().clickable { open = !open }.padding(horizontal = 12.dp, vertical = 12.dp),
            verticalAlignment = Alignment.CenterVertically,
        ) {
            Glyph("ui:bulb", 18.dp, badge = false)
            HGap(8.dp)
            Column(Modifier.weight(1f)) {
                Text("Как пользоваться", fontSize = 14.sp, fontWeight = FontWeight.SemiBold)
                Text(g.title, fontSize = 12.sp, color = extra.dim)
            }
            Icon(if (open) Icons.Default.ExpandLess else Icons.Default.ExpandMore, if (open) "Свернуть" else "Подробная инструкция", tint = extra.dim)
        }
        AnimatedVisibility(open) {
            Column(Modifier.fillMaxWidth().padding(start = 12.dp, end = 12.dp, bottom = 14.dp)) {
                Text(g.about, fontSize = 13.sp, lineHeight = 19.sp)
                g.steps.forEachIndexed { i, s ->
                    Row(Modifier.padding(top = 8.dp)) {
                        Text("${i + 1}.", Modifier.padding(end = 8.dp), fontSize = 13.sp, fontWeight = FontWeight.SemiBold, color = MaterialTheme.colorScheme.primary)
                        Text(s, fontSize = 13.sp, lineHeight = 19.sp)
                    }
                }
                if (g.tips.isNotEmpty()) {
                    Text("Советы", fontSize = 13.sp, fontWeight = FontWeight.SemiBold, modifier = Modifier.padding(top = 12.dp))
                    g.tips.forEach { t -> Text("• $t", fontSize = 13.sp, lineHeight = 19.sp, color = extra.dim, modifier = Modifier.padding(top = 4.dp)) }
                }
            }
        }
    }
}

